export const clone = (o) => structuredClone(o);
export function mergeConfig(input = {}) {
  let c = clone(DEFAULTS);
  for (const k of Object.keys(c))
    if (input[k] !== undefined)
      c[k] = Array.isArray(c[k])
        ? clone(input[k])
        : typeof c[k] === "object"
          ? { ...c[k], ...clone(input[k]) }
          : input[k];
  return c;
}
export function enabled(tenant, key) {
  return (
    tenant.entitlements?.[key] !== false &&
    tenant.config?.visible?.[key] !== false
  );
}
export const human = (s) =>
  s
    .replace(/([A-Z])/g, " $1")
    .replace(/[_.]/g, " ")
    .replace(/^./, (s) => s.toUpperCase());
